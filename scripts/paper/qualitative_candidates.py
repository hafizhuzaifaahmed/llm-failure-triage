"""Qualitative-example candidates for the paper (write-up phase, D-79): reads stored decisions only, no model call.

Two groups, D1-test, S1, judge M1, DEB, PF ground truth, instances in the scored S1 set (D-70):
  kept      -- DEB said PROGRAM_FAULT in all three replicates
  discarded -- DEB said TEST_FAULT in all three replicates
Stable cases only, so an example does not hinge on one sample. Up to three per group, one per project where possible,
ordered by project then instance id (no selection on content). Writes docs/paper/QUALITATIVE_CANDIDATES.md.
"""
import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from triage import config  # noqa: E402
from triage.io_utils import read_jsonl  # noqa: E402

RUN = ROOT / "results" / "runs_local" / "LOCAL_HO_E1E3_M1"
OUT = ROOT / "docs" / "paper" / "QUALITATIVE_CANDIDATES.md"


def main():
    samp = json.loads((config.PROCESSED / "sample_D1_test.json").read_text(encoding="utf-8"))
    keep = set(samp["instance_ids"])
    labels = {l["instance_id"]: l["label"] for l in read_jsonl(config.GT_STORE / "labels_D1.jsonl") if l["instance_id"] in keep}
    aborted = {r["instance_id"] for r in read_jsonl(RUN / "leakage_rejections.jsonl") if r.get("level") == "S1"}
    inst = {i["instance_id"]: i for i in read_jsonl(config.PROCESSED / "instances_D1.jsonl") if i["instance_id"] in keep}
    deb = defaultdict(list)
    for d in read_jsonl(RUN / "decisions.jsonl"):
        if d["arm"] == "DEB" and d["level"] == "S1" and (d.get("variant") or "full") == "full":
            deb[d["instance_id"]].append(d)
    groups = {"kept": [], "discarded": []}
    for iid, ds in sorted(deb.items(), key=lambda kv: (inst[kv[0]]["project"], kv[0])):
        if labels.get(iid) != "PF" or iid in aborted or len(ds) != 3:
            continue
        labs = {d["label_raw"] for d in ds}
        if labs == {"PROGRAM_FAULT"}:
            groups["kept"].append(iid)
        elif labs == {"TEST_FAULT"}:
            groups["discarded"].append(iid)

    def pick(ids):
        out, seen = [], set()
        for iid in ids:                        # one per project first
            if inst[iid]["project"] not in seen:
                out.append(iid)
                seen.add(inst[iid]["project"])
        return (out + [i for i in ids if i not in out])[:3]

    lines = ["# Qualitative-example candidates (D1-test, S1, judge M1, DEB, PF ground truth)", "",
             "Generated by `scripts/paper/qualitative_candidates.py` from stored decisions (no model call). Stable "
             "cases only: the same DEB label in all three replicates. Evidence ids and summary are replicate 0's.", "",
             f"Pool: {len(groups['kept'])} PF instances kept by DEB in all three replicates, "
             f"{len(groups['discarded'])} discarded in all three.", ""]
    for g, title in (("kept", "PF correctly kept by DEB"), ("discarded", "PF wrongly discarded by DEB")):
        lines += [f"## {title}", ""]
        for n, iid in enumerate(pick(groups[g]), 1):
            i, d = inst[iid], sorted(deb[iid], key=lambda x: x["replicate"])[0]
            f = i["failure"]
            lines += [f"### {g[0].upper()}{n}. `{iid}` — {i['bug_name']}, `{i['focal_class'].split('.')[-1]}.{i['focal_method_name']}`", "",
                      f"- Test `{i['method']}`; failure on the buggy version: `{f['exception_class']}` — `{(f.get('message') or '')[:160]}`",
                      f"- Failing line: `{(f.get('failing_test_line_text') or '').strip()[:160]}`",
                      f"- DEB (rep 0): {d['label_raw']}, reason `{d.get('reason_category')}`, cited evidence {d['evidence_ids']}, "
                      f"adjudicator confidence {d.get('confidence')}",
                      f"- DEB summary: {d.get('summary', '').strip()}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(OUT, {k: len(v) for k, v in groups.items()})


if __name__ == "__main__":
    main()
