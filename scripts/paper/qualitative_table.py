"""Qualitative examples chosen by the authors (K1, D2, D3; D-79): verbatim judge text for the paper, from stored decisions.

Reads the replicate-0 DEB|S1 decision of each chosen instance from LOCAL_HO_E1E3_M1 (the replicate the candidate list
showed) and the instance's failure record; no model call, nothing re-scored. Writes
    paper/generated/qualitative.tex          LaTeX macros: verbatim summary, cited evidence ids, labels, instance id
    docs/paper/QUALITATIVE_EXAMPLES.json     the same, plus the full stored decision and failure fields (replication package)
The DEB label is checked to be the same in all three replicates, as the candidate list required.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from triage import config  # noqa: E402
from triage.io_utils import dump_json, read_jsonl  # noqa: E402

RUN = ROOT / "results" / "runs_local" / "LOCAL_HO_E1E3_M1"
CHOSEN = {"A": ("K1", "463cdd07aee29769"), "B": ("D2", "4ef255d5303b254c"), "C": ("D3", "c238fd264c142600")}
TEX = ROOT / "paper" / "generated" / "qualitative.tex"
JSON = ROOT / "docs" / "paper" / "QUALITATIVE_EXAMPLES.json"
LABEL = {"PROGRAM_FAULT": "PF", "TEST_FAULT": "TF", "PF": "PF", "TF": "TF"}


def esc(s: str) -> str:
    rep = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{",
           "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
    return "".join(rep.get(c, c) for c in s)


def main():
    ids = {iid for _, iid in CHOSEN.values()}
    labels = {l["instance_id"]: l["label"] for l in read_jsonl(config.GT_STORE / "labels_D1.jsonl") if l["instance_id"] in ids}
    inst = {i["instance_id"]: i for i in read_jsonl(config.PROCESSED / "instances_D1.jsonl") if i["instance_id"] in ids}
    decs = {}
    for d in read_jsonl(RUN / "decisions.jsonl"):
        if d["instance_id"] in ids and d["arm"] == "DEB" and d["level"] == "S1" and (d.get("variant") or "full") == "full":
            decs.setdefault(d["instance_id"], []).append(d)
    defs, out = [], {"source": str(RUN.relative_to(ROOT).as_posix()) + "/decisions.jsonl", "arm": "DEB", "level": "S1",
                     "judge": "M1 qwen3.5:9b", "replicate_quoted": 0, "examples": []}
    for key, (case, iid) in CHOSEN.items():
        ds = sorted(decs[iid], key=lambda d: d["replicate"])
        assert len(ds) == 3 and len({d["label_raw"] for d in ds}) == 1, (case, iid)
        d0, i = ds[0], inst[iid]
        f = i["failure"]
        defs += [f"\\def\\Qcase{key}{{{case}}}", f"\\def\\Qid{key}{{\\texttt{{{iid}}}}}",
                 f"\\def\\Qbug{key}{{{esc(i['bug_name'])}, \\texttt{{{esc(i['focal_class'].split('.')[-1])}.}}\\allowbreak"
                 f"\\texttt{{{esc(i['focal_method_name'])}}}}}",
                 f"\\def\\Qtruth{key}{{{LABEL[labels[iid]]}}}", f"\\def\\Qdeb{key}{{{LABEL[d0['label_raw']]}}}",
                 f"\\def\\Qev{key}{{{', '.join(esc(e) for e in d0['evidence_ids'])}}}",
                 f"\\def\\Qsum{key}{{``{esc(d0['summary'].strip())}''}}"]
        out["examples"].append({"case": case, "instance_id": iid, "bug": i["bug_name"], "focal_id": i["focal_id"],
                                "test_method": i["method"], "ground_truth": labels[iid],
                                "deb_labels_all_replicates": [d["label_raw"] for d in ds],
                                "failure": {k: f.get(k) for k in ("outcome_type", "exception_class", "message",
                                                                  "expected", "actual", "failing_test_line_text")},
                                "decision_replicate_0": d0})
    TEX.write_text("% generated by scripts/paper/qualitative_table.py from stored decisions -- verbatim, do not edit\n"
                   + "\n".join(defs) + "\n", encoding="utf-8")
    dump_json(JSON, out)
    print(TEX, JSON)


if __name__ == "__main__":
    main()
