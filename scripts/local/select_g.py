"""Step 2 (sequential, D-22) — evaluate one generator candidate on the development split (definitions D-32).

    python scripts/local/select_g.py --model gemma4:26b

Reads data/interim/candidates_<model>/ and data/raw/executions_<model>/ (dev only) and, if present,
results/dev/coverage_<model>.json. Writes results/dev/g_selection_<model>.json with C1, C2, C3 (reported), C4,
P1, bootstrap CIs over focal methods, and the D-22/D-22a verdict.
"""
import argparse
import json
import random
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

from triage import config, javasrc, labeling, preprocess  # noqa: E402
from triage.io_utils import dump_json, sha256_text  # noqa: E402

EXECUTED = ("PF", "TF", "AMB", "PASS", "MISGUIDED")
THRESH = {"C1": 0.50, "C2": 0.50, "P1": 0.03}


def slug(m):
    return m.replace("/", "__").replace(":", "_")


def boot_ci(per_focal: dict, num_key: str, den_key: str, B: int = 10_000, seed: int = 20261101):
    keys = sorted(k for k in per_focal if per_focal[k][den_key] > 0)
    if not keys:
        return [None, None]
    rng = random.Random(seed)
    vals = []
    for _ in range(B):
        s = [keys[rng.randrange(len(keys))] for _ in keys]
        num = sum(per_focal[k][num_key] for k in s)
        den = sum(per_focal[k][den_key] for k in s)
        vals.append(num / den if den else 0.0)
    vals.sort()
    return [vals[int(0.025 * B)], vals[int(0.975 * B) - 1]]


def generated_methods(c):
    """(number of generated test methods, their bodies) for an assembled candidate.

    D-102: a class whose braces do not balance cannot be split into methods. The execution harness already records it
    as `unparseable class` with no executed method; here its methods count as generated by the assembler's own @Test
    count and none as executed, as for a class that compiles on neither version. No body enters the uniqueness count.
    """
    try:
        ms = javasrc.test_methods(c["source"])
    except ValueError:
        return int(c.get("n_tests") or 0), None
    return len(ms), [m.text(c["source"]) for m in ms]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", required=True)
    a = ap.parse_args()
    sl = slug(a.model)
    cdir, edir = config.INTERIM / f"candidates_{sl}", config.RAW / f"executions_{sl}"
    cands = [json.loads(p.read_text()) for p in sorted(cdir.glob("*.json"))]
    execs = {json.loads(p.read_text())["candidate_id"]: json.loads(p.read_text()) for p in sorted(edir.glob("*.json"))}
    per_focal = defaultdict(lambda: Counter())
    per_gen = defaultdict(lambda: Counter())
    labels = Counter()
    bodies = defaultdict(set)
    assembly_fail = unparseable = 0
    for c in cands:
        fid = c["focal_id"]
        if not c.get("assembled"):
            assembly_fail += 1
            per_focal[fid]["assembly_fail"] += 1
            continue
        n_gen, method_bodies = generated_methods(c)
        per_focal[fid]["generated"] += n_gen
        per_gen[c["generation"]]["generated"] += n_gen
        unparseable += method_bodies is None
        for b in method_bodies or ():
            bodies[fid].add(sha256_text(preprocess.normalise_test_body(b)))
        ex = execs.get(c["candidate_id"])
        if ex is None:
            per_focal[fid]["not_executed_classes"] += 1
            continue
        for m in ex["methods"]:
            lab = labeling.label(m)["label"]
            labels[lab] += 1
            if lab in EXECUTED:
                per_focal[fid]["executed"] += 1
                per_gen[c["generation"]]["executed"] += 1
                per_focal[fid]["pass_on_F"] += lab in ("PF", "PASS")
                per_focal[fid]["PF"] += lab == "PF"
    gen = sum(v["generated"] for v in per_focal.values())
    exe = sum(v["executed"] for v in per_focal.values())
    pof = sum(v["pass_on_F"] for v in per_focal.values())
    pf = sum(v["PF"] for v in per_focal.values())
    uniq = sum(len(b) for b in bodies.values())
    c1_by_gen = [per_gen[g]["executed"] / per_gen[g]["generated"] for g in sorted(per_gen) if per_gen[g]["generated"]]
    cov_path = config.ROOT / "results" / "dev" / f"coverage_{sl}.json"
    cov = json.loads(cov_path.read_text()) if cov_path.exists() else None
    feas_path = config.ROOT / "results" / "dev" / "feasibility" / f"{sl}.json"
    feas = json.loads(feas_path.read_text()) if feas_path.exists() else None
    res = {
        "model": a.model, "focal_methods": len(per_focal), "generations": len(cands), "assembly_failures": assembly_fail,
        "unparseable_classes": unparseable,
        "generated_methods": gen, "executed_methods": exe, "labels_method_level": dict(labels),
        "C1": exe / gen if gen else None, "C1_ci95": boot_ci(per_focal, "executed", "generated"),
        "C2": pof / exe if exe else None, "C2_ci95": boot_ci(per_focal, "pass_on_F", "executed"),
        "P1": pf / exe if exe else None, "P1_ci95": boot_ci(per_focal, "PF", "executed"),
        "C3_coverage": cov["summary"] if cov else "not computed",
        "C4_uniqueness": uniq / gen if gen else None,
        "C4_stability_sd_C1_across_generations": statistics.pstdev(c1_by_gen) if len(c1_by_gen) > 1 else None,
        "C1_by_generation": c1_by_gen,
        # D-39: validity screens, does not eliminate; D-40: available RAM is a per-session precondition, not a
        # model property. Model feasibility for G = context 8192 and thinking off empty.
        "feasibility_passed": bool(feas and feas["verdict"]["context_length_8192"]
                                   and feas["verdict"]["thinking_off_empty_all"]),
        "feasibility_record": None if not feas else {k: feas["verdict"][k] for k in
                                                     ("context_length_8192", "thinking_off_empty_all", "valid_rate",
                                                      "ram_free_ge_4gib", "passes")},
        "thresholds": THRESH, "rule": "D-22/D-22a: feasibility AND P1>=3% AND C1>=50% AND C2>=50%",
    }
    res["verdict"] = {
        "feasibility": res["feasibility_passed"],
        "P1": res["P1"] is not None and res["P1"] >= THRESH["P1"],
        "C1": res["C1"] is not None and res["C1"] >= THRESH["C1"],
        "C2": res["C2"] is not None and res["C2"] >= THRESH["C2"],
    }
    res["selected"] = all(res["verdict"].values())
    dump_json(config.ROOT / "results" / "dev" / f"g_selection_{sl}.json", res)
    print(json.dumps({k: res[k] for k in ("generated_methods", "executed_methods", "labels_method_level", "C1",
                                           "C1_ci95", "C2", "C2_ci95", "P1", "P1_ci95", "C4_uniqueness", "verdict",
                                           "selected")}, indent=1))


if __name__ == "__main__":
    main()
