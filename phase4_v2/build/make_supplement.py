"""Build PHASE4_FINAL_SUPPLEMENT.tex (IEEE format) from the reviewed _v2 manuscript (read only).

Run from the repository root:  python phase4_v2/build/make_supplement.py
The supplement holds, unchanged in numbers:
  * every appendix of PHASE4_RESEARCH_PAPER_v2.tex (A deviations ... I artefact traceability, plus the qualitative
    table), except the floats that moved into the final paper (their references resolve to the paper through xr);
  * a final appendix with the full report of the registered confirmation and the exploratory audit analyses,
    which the final paper shortens (V2 sections 9 and 10, without the tables the paper prints and without the
    WDP paragraph, which the paper prints).
Wording changes: the class is IEEEtran; tables and figures are numbered S1, S2, ... in one sequence; the V2
instructor-feedback placeholder is replaced by the authors' statement of 2026-11-14 (no comments were given).
Cross-references to the final paper's labels resolve through xr-hyper (PHASE4_FINAL_PAPER_labels.aux).
"""
import os
import re

HERE = os.path.join(os.getcwd(), "phase4_v2")
V2 = os.path.join(HERE, "PHASE4_RESEARCH_PAPER_v2.tex")
OUT = os.path.join(HERE, "PHASE4_FINAL_SUPPLEMENT.tex")
MOVED = ["tab:base", "tab:quant", "tab:abl", "tab:status"]          # now printed in the final paper
IN_PAPER = ["tab:flow", "tab:family", "tab:rules"]                  # printed in the final paper's results
BS = "\\"


def drop_float_with_label(text, label):
    i = text.find(BS + "label{" + label + "}")
    if i < 0:
        raise SystemExit("label not found: " + label)
    m = list(re.finditer(r"\\begin\{(table\*?|figure\*?)\}", text[:i]))[-1]
    env = m.group(1)
    end = text.index(BS + "end{" + env + "}", i) + len(BS + "end{" + env + "}")
    return text[:m.start()] + "% (float " + label + " is printed in the final paper)\n" + text[end:]


def preamble(src):
    pre = src[:src.index(BS + "begin{document}")]
    pre = re.sub(r"(?m)^%%.*\n", "", pre)
    pre = pre.replace(BS + "documentclass[pdflatex,iicol,sn-mathphys-num]{sn-jnl}", BS + "documentclass[journal]{IEEEtran}", 1)
    for pkg in ("amsthm", "mathrsfs", "manyfoot"):
        pre = pre.replace(BS + "usepackage{" + pkg + "}%\n", "", 1)
    pre = pre.replace(BS + "usepackage[title]{appendix}%\n", "", 1)  # IEEEtran has its own appendices command
    extra ="\n".join([BS + "usepackage{url}", BS + "usepackage{xr-hyper}",
                       BS + "externaldocument{PHASE4_FINAL_PAPER_labels}", BS + "usepackage[hidelinks]{hyperref}",
                       BS + "renewcommand{" + BS + "thetable}{S" + BS + "arabic{table}}",
                       BS + "renewcommand{" + BS + "thefigure}{S" + BS + "arabic{figure}}", ""])
    pre = pre.replace(BS + "newcolumntype{Y}", extra + BS + "newcolumntype{Y}", 1)
    assert "IEEEtran" in pre and "xr-hyper" in pre
    return pre


def main():
    src = open(V2, encoding="utf-8").read()
    header = ("%% Supplementary material of the final Phase 4 paper (IEEE format). GENERATED by\n"
              "%% phase4_v2/build/make_supplement.py from PHASE4_RESEARCH_PAPER_v2.tex (read only); do not edit by hand.\n")
    pre = preamble(src)

    apps = src[src.index(BS + "begin{appendices}"):src.index(BS + "end{appendices}")]
    for lab in MOVED:
        apps = drop_float_with_label(apps, lab)
    # one S-numbered sequence for the whole supplement (IEEE style), not a restart per appendix
    apps = apps.replace(BS + "setcounter{table}{0}" + BS + "setcounter{figure}{0}", "")
    apps = apps.replace("{" + BS + "renewcommand{" + BS + "thetable}{B1}" + BS + "renewcommand{" + BS + "theHtable}{B1.qual}", "{")
    # the authors' statement of 2026-11-14 replaces the V2 placeholder
    marker = BS + "item " + BS + "textbf{Instructor feedback on Phase~2.}"
    i = apps.index(marker)
    j = apps.index("\n", i)
    apps = (apps[:i] + marker + " The instructor gave no comments on the Phase~2 presentation, so no change was made "
            "in response to feedback." + apps[j:])

    # V2 sections 9 and 10: the registered confirmation in full and the exploratory audit analyses
    a = src.index(BS + "section{Registered Confirmation}")
    b = src.index("%% WDP (D-151")
    conf = src[a:b]
    stage_b = src[src.index(BS + "paragraph{Stage B (designed before"):src.index(BS + "section{Discussion}")]
    stage_b = stage_b.replace("%% " + "=" * 85, "")
    pilot = src[src.index(BS + "begin{table}[t]", src.index(BS + "paragraph{Pilot (exploratory).}")):
                src.index(BS + "end{table}", src.index(BS + "label{tab:pilotconf}")) + len(BS + "end{table}")]
    for lab in IN_PAPER:
        conf = drop_float_with_label(conf, lab)
    conf = conf.replace(BS + "section{Registered Confirmation}" + BS + "label{sec:confirm}",
                        BS + "section{Registered confirmation and exploratory analyses: full report}" + BS +
                        "label{app:confirmfull}\nThis appendix reproduces, unchanged in numbers, the full report of the "
                        "registered confirmation (Section~" + BS + "ref{sec:confirm} of the paper prints its family, rules "
                        "and population) and the exploratory audit analyses that Section~" + BS + "ref{sec:surviving} "
                        "summarises.\n\n" + BS + "subsection*{The registered confirmation}\n")
    conf = conf.replace(BS + "section{What the Surviving Signal Is (Exploratory)}" + BS + "label{sec:surviving}",
                        BS + "subsection*{What the surviving signal is (exploratory)}")
    conf = conf.replace("%% " + "=" * 85, "")
    extra = (conf + pilot + "\n\n" + stage_b).rstrip() + "\n"

    front = (BS + "begin{document}\n\n"
             + BS + "title{Supplementary Material for ``Program Fault or Test Fault? LLM Triage of Failing Generated "
             "Unit Tests and a Registered Test of Mutation Evidence''}\n\n"
             + BS + "author{Hafiz~Huzaifa~Ahmed and Saad~Ilyas" + BS + "thanks{The authors are with the Department of "
             "Artificial Intelligence " + BS + "& Data Science, School of Computing, FAST-NUCES.}}\n\n"
             + BS + "maketitle\n\n"
             + BS + "begin{abstract}This supplement holds the deviations from the original design, the extended result "
             "tables, the post hoc, exploratory and robustness analyses, the registration details, the artefact "
             "traceability and the full report of the registered confirmation. Tables and figures numbered S1, S2, "
             + BS + "ldots{} are in this supplement; Roman-numbered tables and section numbers refer to the main paper. "
             "Every number comes from the same generated file as the main paper. Evidence status is stated beside "
             "every result; Table~" + BS + "ref{tab:status} of the main paper summarises it." + BS + "end{abstract}\n\n")
    apps = apps.replace(BS + "begin{appendices}", BS + "appendices", 1)
    body = (front + apps + extra + "\n" + BS + "bibliographystyle{IEEEtran}\n"
            + BS + "bibliography{references_v2}\n\n" + BS + "end{document}\n")
    out = header + pre + body
    assert "@isb.nu.edu.pk" not in out and BS + "TODO{" not in body
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
